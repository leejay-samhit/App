# ------------------ Payment (Mock) ------------------
async def _credit_payout(sponsor_user: Dict[str, Any]):
    """Credit ₹PAYOUT_PER_LEVEL to sponsor, log transaction."""
    amount = PAYOUT_PER_LEVEL
    await db.users.update_one(
        {"id": sponsor_user["id"]},
        {
            "$inc": {
                "wallet_balance": amount,
                "total_earned": amount,
                "payouts_received": 1,
            }
        },
    )
    await db.transactions.insert_one({
        "id": str(uuid.uuid4()),
        "user_id": sponsor_user["id"],
        "type": "referral_payout",
        "amount": amount,
        "status": "credited",
        "description": f"Referral payout for completing 1+{DIRECTS_REQUIRED} cycle",
        "created_at": now_utc().isoformat(),
    })


@api_router.post("/payment/register-fee")
async def pay_registration_fee(user: Dict[str, Any] = Depends(get_current_user)):
    """Mock registration fee payment. Activates account & triggers referral payout."""
    if user.get("registration_paid"):
        raise HTTPException(status_code=400, detail="Registration fee already paid")

    txn_id = str(uuid.uuid4())
    await db.users.update_one({"id": user["id"]}, {"$set": {"registration_paid": True}})
    await db.transactions.insert_one({
        "id": txn_id,
        "user_id": user["id"],
        "type": "registration_fee",
        "amount": REGISTRATION_FEE,
        "status": "paid",
        "description": "Registration fee (mocked)",
        "created_at": now_utc().isoformat(),
    })

    # Update sponsor's direct count and trigger payout if 4 reached
    sponsor_id = user.get("sponsor_id")
    if sponsor_id:
        sponsor = await db.users.find_one({"id": sponsor_id})
        if sponsor:
            new_count = sponsor.get("direct_referrals_count", 0) + 1
            await db.users.update_one(
                {"id": sponsor_id},
                {"$inc": {"direct_referrals_count": 1}}
            )
            # Recursive 1+4: payout each time direct count reaches a multiple of 4
            if new_count % DIRECTS_REQUIRED == 0:
                sponsor_fresh = await db.users.find_one({"id": sponsor_id})
                await _credit_payout(sponsor_fresh)

    return {"ok": True, "transaction_id": txn_id, "amount": REGISTRATION_FEE}


